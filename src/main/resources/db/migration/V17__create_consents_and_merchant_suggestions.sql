-- Журнал согласий (ADR-0010): строки только добавляются, текущее состояние — последняя строка по документу.
CREATE TABLE user_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    document VARCHAR(30) NOT NULL,
    version VARCHAR(20) NOT NULL,
    granted BOOLEAN NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_consents_account FOREIGN KEY (account_id) REFERENCES user_accounts (id)
);
CREATE INDEX idx_user_consents_account_id ON user_consents (account_id);

-- Названия для пополнения общей базы. Намеренно только название: ни владельца, ни суммы, ни даты.
CREATE TABLE merchant_suggestions (
    normalized_name VARCHAR(1000) PRIMARY KEY,
    status VARCHAR(10) NOT NULL,
    CONSTRAINT chk_merchant_suggestions_status CHECK (status IN ('NEW', 'REJECTED'))
);
