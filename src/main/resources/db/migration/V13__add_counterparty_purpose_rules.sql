-- Личные правила назначения по контрагенту (ADR-0003). Ключ контрагента может содержать имя человека,
-- поэтому правила хранятся отдельно от общей базы продавцов и в неё не попадают.
CREATE TABLE counterparty_purpose_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    counterparty_key VARCHAR(1000) NOT NULL,
    direction VARCHAR(10) NOT NULL,
    purpose VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_counterparty_purpose_rules_key_direction UNIQUE (counterparty_key, direction),
    CONSTRAINT chk_counterparty_purpose_rules_direction CHECK (direction IN ('INFLOW', 'OUTFLOW')),
    CONSTRAINT chk_counterparty_purpose_rules_purpose CHECK (purpose <> 'UNKNOWN')
);
